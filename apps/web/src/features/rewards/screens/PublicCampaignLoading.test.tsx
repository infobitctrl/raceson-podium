import {act, fireEvent, render, screen, within} from '@testing-library/react';
import {MemoryRouter, Route, Routes} from 'react-router-dom';
import {expect, it, vi} from 'vitest';
import type {ReactNode} from 'react';
import type {PublicSponsorCampaign as Campaign, PublicRewardPage} from '@raceson/domain/rewards/public-campaign';
import {I18nProvider} from '@/shared/i18n/I18nProvider';
import PublicSponsorCampaign from './PublicSponsorCampaign';
const api = vi.hoisted(() => ({live: vi.fn(), snapshot: vi.fn(), rewards: vi.fn()}));
vi.mock('../data/publicCampaign', () => ({readPublicCampaign: api.live, readPublicCampaignSnapshot: api.snapshot, readPublicRewards: api.rewards}));
vi.mock('@/lib/auth', () => ({useAuth: () => ({account: null, user: null})}));
vi.mock('../components/CampaignSponsor', () => ({CampaignSponsor: () => <span>Synthetic sponsor</span>, CampaignSponsorProvider: ({children}: {children: ReactNode}) => children}));
const pot = (slot: number) => ({slot, name: slot ? 'Round 1' : 'League', amountWei: '50', state: 3, paused: false, allocatedWei: '50', paidWei: '0', remainingWei: '50', returnedWei: '0', claimDeadline: '1800001000', groups: [{name: 'Open', amountWei: '50'}]});
const campaign: Campaign = {id: 'campaign', name: 'Synthetic league', chainId: 31337, budgetWei: '100', address: '0x'+'11'.repeat(20), fundingHash: '0x'+'aa'.repeat(32), blockNumber: '100', blockTimestamp: '1800000000', pots: [pot(0), pot(1)]};
function page(slot: number, blockNumber = '100'): PublicRewardPage {return {campaignId: campaign.id, chainId: 31337, slot, offset: 0, sort: 'reward', direction: 'asc', total: 1, availability: 'open', blockNumber, blockTimestamp: '1800000000', rows: [{id: '0x'+String(slot+1).repeat(64), number: 1, kind: 'athlete', amountWei: '50', status: 'unclaimed', display: {name: slot ? 'Round athlete' : 'League athlete', club: null, timeMs: null}, breakdown: [{category: 'Open', place: 1, amountWei: '50'}]}]};}
const ui = <I18nProvider initialLocale="en"><MemoryRouter initialEntries={['/rewards/campaigns/campaign/public?pot=1']}><Routes><Route path="/rewards/campaigns/:id/public" element={<PublicSponsorCampaign/>}/></Routes></MemoryRouter></I18nProvider>;
it('renders budgets early, reuses verification, and immediately restores a visited round through refresh and retry', async () => {
  let finish!: (value: Campaign) => void;
  api.live.mockReturnValueOnce(new Promise(resolve => {finish = resolve;}));
  api.snapshot.mockResolvedValue({campaign, selection: null, publishedAt: '2026-10-11T00:00:00Z'});
  api.rewards.mockImplementation(async (_id, slot) => page(slot));
  render(ui);
  expect(await screen.findByText('Published snapshot')).toBeVisible();
  expect(screen.getByRole('heading', {name: 'Prize pool allocation'})).toBeVisible();
  expect(api.rewards).not.toHaveBeenCalled();
  await act(async () => finish(campaign));
  expect(await screen.findByText('Round athlete')).toBeVisible();
  expect(api.rewards.mock.calls[0][6]).toBe('100');
  const choose = (name: RegExp) => fireEvent.click(within(screen.getByRole('group', {name: 'Prize pots'})).getByRole('button', {name}));
  choose(/League/); expect(await screen.findByText('League athlete')).toBeVisible();
  let reject!: () => void;
  api.rewards.mockImplementationOnce(() => new Promise((_, fail) => {reject = () => fail(Error('offline'));}));
  choose(/Round 1/);
  expect(screen.getByText('Round athlete')).toBeVisible();
  expect(screen.queryByText('League athlete')).not.toBeInTheDocument();
  expect(screen.getByRole('button', {name: '#1 · Round athlete, 0 test MON, Unclaimed'})).toBeVisible();
  expect(api.rewards.mock.calls[2][6]).toBeUndefined();
  expect(screen.getByText('Checking reward status…')).toBeVisible();
  await act(async () => reject());
  expect(screen.getByRole('alert')).toHaveTextContent('last verified rewards');
  expect(screen.getByText('Round athlete')).toBeVisible();
  api.rewards.mockResolvedValueOnce(page(1, '101'));
  fireEvent.click(screen.getByRole('button', {name: 'Retry reward status'}));
  await act(async () => {});
  expect(screen.queryByRole('alert')).not.toBeInTheDocument();
  expect(api.rewards.mock.calls[3][6]).toBeUndefined();
  api.live.mockReturnValueOnce(new Promise(resolve => {finish = resolve;}));
  fireEvent.click(screen.getByRole('button', {name: 'Refresh status'}));
  expect(screen.getByText('Round athlete')).toBeVisible();
  expect(api.rewards).toHaveBeenCalledTimes(4);
  await act(async () => finish({...campaign, blockNumber: '102'}));
  expect(await screen.findByText('Round athlete')).toBeVisible();
  // A manual reward retry stays fresh even after a later campaign refresh.
  expect(api.rewards.mock.calls[4][6]).toBeUndefined();
});
