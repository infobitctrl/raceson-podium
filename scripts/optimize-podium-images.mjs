import sharp from 'sharp';
import {mkdir, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';

// Rebuild presentation assets from the retained originals. No crop, metadata,
// source-image replacement, or remote fetch: CSS retains the existing framing.
const root = fileURLToPath(new URL('../', import.meta.url));
const assets = join(root, 'apps/web/src/features/rewards/assets');
const output = join(assets, 'optimized');
await mkdir(output, {recursive:true});
const imports = [], entries = [], photos = ['sitrail-valley.jpeg','vrpolje.jpeg','trtar.png','raslina.jpeg','subicevac.jpeg'];
for (const [index, name] of photos.entries()) {
  const source = join(assets, name), metadata = await sharp(source).metadata();
  const widths = [...new Set([480, 960, Math.min(1600, metadata.width)])];
  const variants = [];
  for (const width of widths) {
    const file = `${name.split('.')[0]}-${width}.webp`, symbol = `photo${index}_${width}`;
    const {width:actualWidth, height} = await sharp(source).rotate().resize({width, withoutEnlargement:true}).webp({quality:80, effort:6}).toFile(join(output,file));
    imports.push(`import ${symbol} from '../assets/optimized/${file}';`);
    variants.push(`{src:staticAssetUrl(${symbol}),width:${actualWidth},height:${height}}`);
  }
  entries.push(`  [${variants.join(',')}],`);
}
await sharp(join(assets,'sitrail-wordmark.png')).resize({width:640,withoutEnlargement:true}).webp({lossless:true,effort:6}).toFile(join(output,'sitrail-wordmark.webp'));
await sharp(join(root,'apps/web/src/assets/brand/podium-trisport-logo.png')).resize({width:560,withoutEnlargement:true}).webp({lossless:true,effort:6}).toFile(join(output,'podium-logo.webp'));
await writeFile(join(root,'apps/web/src/features/rewards/model/artworkVariants.ts'), `// Generated by scripts/optimize-podium-images.mjs; retain originals for regeneration.\nimport {staticAssetUrl} from '@/lib/static-asset';\n${imports.join('\n')}\n\nexport const artworkVariants = [\n${entries.join('\n')}\n] as const;\n`);
